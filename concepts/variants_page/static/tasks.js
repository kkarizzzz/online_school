// Генератор заданий ЕГЭ (профиль) для концепта: по номеру задания и зерну — условие и числовой ответ.
// Одно и то же зерно всегда даёт одно и то же задание, поэтому вариант стабилен между попытками.
// Позже задания будут браться из банка на сервере.
//
// makeTask(number, seed) -> { number, text, answer }
// text — HTML с формулами в $...$ (KaTeX), answer — число

(() => {
    /** Зерно-строка -> генератор случайных чисел [0, 1) (mulberry32) */
    function rng(seed) {
        let h = 1779033703 ^ seed.length;
        for (let i = 0; i < seed.length; i++) {
            h = Math.imul(h ^ seed.charCodeAt(i), 3432918353);
            h = (h << 13) | (h >>> 19);
        }
        let a = h >>> 0;
        return () => {
            a = (a + 0x6D2B79F5) | 0;
            let t = Math.imul(a ^ (a >>> 15), 1 | a);
            t = (t + Math.imul(t ^ (t >>> 7), 61 | t)) ^ t;
            return ((t ^ (t >>> 14)) >>> 0) / 4294967296;
        };
    }

    const int = (r, min, max) => min + Math.floor(r() * (max - min + 1));
    const pick = (r, arr) => arr[Math.floor(r() * arr.length)];
    const round = (x) => Number(x.toFixed(6));
    /** Число в условии: десятичная запятая, как на ЕГЭ */
    const num = (x) => String(round(x)).replace('.', '{,}');
    /** Слагаемое со знаком: sign(3) -> «+ 3», sign(-3) -> «- 3» */
    const sign = (x) => (x < 0 ? `- ${-x}` : `+ ${x}`);
    const gcd = (a, b) => (b ? gcd(b, a % b) : a);

    const TRIPLES = [[3, 4, 5], [5, 12, 13], [6, 8, 10], [8, 15, 17], [9, 12, 15], [7, 24, 25], [20, 21, 29]];

    /** Число корней серий x = offset + k·period (в долях π) на отрезке [0; n·π] */
    function countRoots(series, n) {
        const roots = new Set();
        for (const [offset, period] of series) {
            for (let x = offset; x <= n + 1e-9; x += period) if (x >= -1e-9) roots.add(round(x));
        }
        return roots.size;
    }

    const GENERATORS = {
        1: (r) => {
            const [a, b, c] = pick(r, TRIPLES);
            return r() < 0.5
                ? { text: `В прямоугольном треугольнике катеты равны $${a}$ и $${b}$. Найдите гипотенузу.`, answer: c }
                : { text: `В прямоугольном треугольнике гипотенуза равна $${c}$, один из катетов равен $${a}$. Найдите другой катет.`, answer: b };
        },
        2: (r) => {
            const [x1, y1, x2, y2] = [int(r, -6, 6), int(r, -6, 6), int(r, -6, 6), int(r, -6, 6)];
            return {
                text: `Даны векторы $\\vec a(${x1};\\ ${y1})$ и $\\vec b(${x2};\\ ${y2})$. Найдите скалярное произведение $\\vec a \\cdot \\vec b$.`,
                answer: x1 * x2 + y1 * y2,
            };
        },
        3: (r) => {
            const a = int(r, 2, 7);
            return { text: `Объём куба равен $${a ** 3}$. Найдите площадь его поверхности.`, answer: 6 * a * a };
        },
        4: (r) => {
            const n = pick(r, [20, 25, 40, 50]);
            const k = int(r, 1, n - 1);
            return {
                text: `В урне $${n}$ шаров, из них $${k}$ красных, остальные — синие. Найдите вероятность того, что случайно вынутый шар окажется красным.`,
                answer: round(k / n),
            };
        },
        5: (r) => {
            const p1 = pick(r, [0.5, 0.6, 0.7, 0.8, 0.9]);
            const p2 = pick(r, [0.5, 0.6, 0.7, 0.8, 0.9]);
            return {
                text: `Два стрелка независимо друг от друга стреляют по мишени. Вероятность попадания первого равна $${num(p1)}$, второго — $${num(p2)}$. Найдите вероятность того, что оба промахнутся.`,
                answer: round((1 - p1) * (1 - p2)),
            };
        },
        6: (r) => {
            const b = int(r, 2, 6), a = int(r, 1, 9);
            return { text: `Найдите корень уравнения $\\log_2(x + ${a}) = ${b}$.`, answer: 2 ** b - a };
        },
        7: (r) => {
            const m = int(r, 3, 9), n = int(r, 2, 8), e = int(r, 1, 8);
            return {
                text: `Найдите значение выражения $\\dfrac{2^{${m}} \\cdot 2^{${n}}}{2^{${m + n - e}}}$.`,
                answer: 2 ** e,
            };
        },
        8: (r) => {
            const p = 2 * int(r, 1, 8), q = int(r, -9, 9);
            return { text: `Найдите точку минимума функции $y = x^2 - ${p}x ${sign(q)}$.`, answer: p / 2 };
        },
        9: (r) => {
            const I = int(r, 2, 6), R = int(r, 3, 12);
            return {
                text: `Мощность постоянного тока (в ваттах) вычисляется по формуле $P = I^2 R$, где $I$ — сила тока (в амперах), $R$ — сопротивление (в омах). Найдите сопротивление $R$, если $P = ${I * I * R}$ Вт, а $I = ${I}$ А. Ответ дайте в омах.`,
                answer: R,
            };
        },
        10: (r) => {
            const v1 = 10 * int(r, 4, 9), v2 = 10 * int(r, 4, 9), t = int(r, 1, 5);
            return {
                text: `Из двух городов, расстояние между которыми $${(v1 + v2) * t}$ км, одновременно навстречу друг другу выехали два автомобиля со скоростями $${v1}$ км/ч и $${v2}$ км/ч. Через сколько часов они встретятся?`,
                answer: t,
            };
        },
        11: (r) => {
            const k = pick(r, [-4, -3, -2, -1, 1, 2, 3, 4]), b = int(r, -5, 5);
            const x1 = int(r, -4, 0), x2 = int(r, 1, 5);
            return {
                text: `Прямая $y = kx + b$ проходит через точки $A(${x1};\\ ${k * x1 + b})$ и $B(${x2};\\ ${k * x2 + b})$. Найдите $k$.`,
                answer: k,
            };
        },
        12: (r) => {
            const p = 2 * int(r, 1, 6), q = int(r, -8, 8);
            return {
                text: `Найдите наибольшее значение функции $y = -x^2 + ${p}x ${sign(q)}$.`,
                answer: q + (p * p) / 4,
            };
        },
        13: (r) => {
            const n = int(r, 2, 6);
            const [eq, series] = pick(r, [
                ['2\\sin^2 x - \\sin x = 0', [[0, 1], [1 / 6, 2], [5 / 6, 2]]],
                ['2\\cos^2 x + \\cos x = 0', [[1 / 2, 1], [2 / 3, 2], [4 / 3, 2]]],
            ]);
            return {
                text: `а) Решите уравнение $${eq}$.<br>б) Найдите количество корней этого уравнения, принадлежащих отрезку $[0;\\ ${n}\\pi]$. В ответ запишите число корней.`,
                answer: countRoots(series, n),
            };
        },
        14: (r) => {
            const [a, h, l] = pick(r, [[4, 1, 3], [8, 2, 6], [8, 7, 9], [12, 3, 9], [12, 7, 11]]);
            return {
                text: `В правильной четырёхугольной пирамиде $SABCD$ сторона основания равна $${a}$, а высота равна $${h}$. Найдите длину бокового ребра.`,
                answer: l,
            };
        },
        15: (r) => {
            const a = int(r, -6, 3), b = a + int(r, 2, 9);
            return r() < 0.5
                ? { text: `Найдите количество целых решений неравенства $(x ${sign(-a)})(x ${sign(-b)}) \\le 0$.`, answer: b - a + 1 }
                : { text: `Найдите количество целых решений неравенства $\\dfrac{x ${sign(-a)}}{x ${sign(-b)}} \\le 0$.`, answer: b - a };
        },
        16: (r) => {
            const s = 100000 * int(r, 1, 9), p = pick(r, [10, 20]);
            return {
                text: `В январе в банк положили $${s.toLocaleString('ru-RU').replace(/\s/g, '\\ ')}$ рублей. Каждый год сумма вклада увеличивается на $${p}\\%$. Какой будет сумма вклада через два года? Ответ дайте в рублях.`,
                answer: round(s * (1 + p / 100) ** 2),
            };
        },
        17: (r) => {
            const [a, b, c] = pick(r, TRIPLES);
            return {
                text: `В прямоугольном треугольнике катеты равны $${a}$ и $${b}$. Найдите радиус вписанной окружности.`,
                answer: (a + b - c) / 2,
            };
        },
        18: (r) => {
            const k = int(r, 2, 9);
            return {
                text: `Найдите наибольшее значение параметра $a$, при котором уравнение $x^2 + ax + ${k * k} = 0$ имеет ровно один корень.`,
                answer: 2 * k,
            };
        },
        19: (r) => {
            let p, q;
            do { p = pick(r, [3, 4, 5, 7, 9, 11]); q = pick(r, [3, 4, 5, 7, 9, 11]); } while (p === q || gcd(p, q) !== 1);
            const r1 = int(r, 1, p - 1), r2 = int(r, 1, q - 1);
            let n = 1;
            while (n % p !== r1 || n % q !== r2) n++;
            return {
                text: `Найдите наименьшее натуральное число, которое при делении на $${p}$ даёт остаток $${r1}$, а при делении на $${q}$ — остаток $${r2}$.`,
                answer: n,
            };
        },
    };

    window.makeTask = (number, seed) => ({ number, ...GENERATORS[number](rng(seed)) });
})();
