"""
Номер ЕГЭ для задания ФИПИ. В открытом банке номера нет — только КЭС и тип ответа,
поэтому решаем по КЭС, наличию рисунка и словам условия.
"""
import re


def _has(text: str, *words: str) -> bool:
    return any(w in text for w in words)


def exam_number(task: dict) -> int | None:
    kes = set(task['kes'])
    sections = {k.split('.')[0] for k in kes}
    text = task['condition']
    low = text.lower()
    picture = bool(task['images'])

    if not task['short']:
        if _has(low, 'решите уравнение', 'решите систему уравнений') or (
                '2.3' in kes and 'уравнени' in low and 'параметр' not in low and 'значения $a' not in low):
            return 13
        if '2.10' in kes or re.search(r'значения (?:параметра )?(?:\$a\$|\*a\*)', low):
            return 18
        if _has(low, 'решите неравенство'):
            return 15
        if _has(low, 'кредит', 'вклад', 'банк', 'млн рублей', 'тыс. рублей', 'прибыль', 'завод', 'фабрик', 'акци', 'ценные бумаги', 'инвест'):
            return 16
        if sections & {'7'}:
            if kes & {'7.2', '7.3', '7.4'} or _has(low, 'пирамид', 'призм', 'куб', 'параллелепипед', 'цилиндр', 'конус', 'шар', 'плоскость'):
                return 14
            return 17
        if kes & {'1.1', '1.2'} or _has(low, 'а) можно ли', 'а) может ли', 'натуральн'):
            return 19
        return None

    # краткий ответ
    if '7.5' in kes:
        return 2
    if kes & {'7.3', '7.4'}:
        return 3
    if '7.1' in kes:
        return 1
    if '6.2' in kes:
        return 5 if _has(low, 'независим', 'условн', 'хотя бы', 'не больше одного', 'по очереди', 'дважды', 'два раза',
                         'три раза', 'дважды', 'оба', 'обе', 'подряд', 'и при этом', 'если известно') else 4
    if kes & {'4.1', '4.2'} or _has(low, 'производн', 'первообразн', 'касательн'):
        if picture or _has(low, 'изображ', 'на рисунке'):
            return 8
        if _has(low, 'наибольшее значение', 'наименьшее значение', 'точку максимума', 'точку минимума'):
            return 12
        return 8
    if low.startswith(('найдите корень уравнения', 'решите уравнение', 'найдите корни уравнения')):
        return 6
    if picture and (kes & {'3.1', '3.2', '3.3', '3.5'} or _has(low, 'график')):
        return 11
    if _has(low, 'найдите значение выражения', 'найдите значение', 'вычислите'):
        return 7
    if _has(low, 'формул', 'зависимость', 'по закону', 'вычисляется', 'определяется', 'задаётся', 'описывается'):
        return 9
    if _has(low, 'км/ч', 'рабоч', 'бассейн', 'труб', 'процент', 'сплав', 'раствор', 'смес', 'катер', 'теплоход',
           'велосипедист', 'автомобил', 'поезд', 'деталей', 'путь', 'заказ', 'выручк', 'стоил', 'вклад', 'дней'):
        return 10
    if kes & {'2.1', '2.2', '2.4', '2.3', '2.5', '2.9'}:
        return 9 if '$' in text else 10  # с формулой — прикладная задача, без неё — текстовая
    if kes & {'1.3', '1.4', '1.5', '1.6', '1.8', '1.2', '1.1'}:
        return 7
    return None
