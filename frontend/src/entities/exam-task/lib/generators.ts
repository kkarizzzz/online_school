/** Корни серий x = offset + k·period (в долях π) на отрезке [0; n·π], по возрастанию */
function rootsOn(series: number[][], n: number): number[] {
    const roots = new Set<number>();
    for (const [offset, period] of series) {
        for (let x = offset; x <= n + 1e-9; x += period) if (x >= -1e-9) roots.add(round(x));
    }
    return [...roots].sort((a, b) => a - b);
}

/** Доля π → TeX: 5/6 → «\frac{5\pi}{6}», 2 → «2\pi», 0 → «0» */
function piFrac(x: number): string {
    let n = Math.round(x * 6), d = 6;
    if (!n) return '0';
    const g = gcd(n, d);
    n /= g;
    d /= g;
    const top = `${n === 1 ? '' : n}\\pi`;
    return d === 1 ? top : `\\frac{${top}}{${d}}`;
}

