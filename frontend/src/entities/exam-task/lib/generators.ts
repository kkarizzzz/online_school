type Generated = Omit<ExamTask, 'number'>;

const round = (x: number): number => Number(x.toFixed(6));
/** Число в условии: десятичная запятая, как на ЕГЭ */
const num = (x: number): string => String(round(x)).replace('.', '{,}');
/** Слагаемое со знаком: sign(3) → «+ 3», sign(-3) → «- 3» */
const sign = (x: number): string => (x < 0 ? `- ${-x}` : `+ ${x}`);
/** Число в формуле, отрицательное — в скобках: par(-3) → «(-3)» */
const par = (x: number): string => (x < 0 ? `(${x})` : `${x}`);
/** Большое число с разрядами: 1210000 → «1\ 210\ 000» */
const big = (x: number): string => round(x).toLocaleString('ru-RU').replace(/\s/g, '\\ ');
const gcd = (a: number, b: number): number => (b ? gcd(b, a % b) : a);

