const PART1 = 12;
const TODAY = new Date('2026-10-07').getTime();

/** Сложность: в первой части в основном база, во второй — сложнее, «гробы» только там */
function levelOf(r: Rng, n: number): BankLevel {
    const x = r();
    if (n <= PART1) return x < 0.5 ? 'base' : x < 0.85 ? 'medium' : 'hard';
    return x < 0.15 ? 'base' : x < 0.5 ? 'medium' : x < 0.85 ? 'hard' : 'coffin';
}

const SOLVED_RANGE: Record<BankLevel, [number, number]> = {
    base: [600, 4200], medium: [250, 2400], hard: [60, 900], coffin: [5, 180],
};

function tasksOf(n: ExamTaskNumber, topic: TopicDef): BankTask[] {
    const r = seededRng(`${n}:${topic.id}`);
    const count = int(r, 5, 12);
    return Array.from({ length: count }, (_, i) => {
        const meta = seededRng(`${n}:${topic.id}:${i}:meta`);
        const level = levelOf(meta, n);
        const date = new Date(TODAY - int(meta, 0, 400) * 86400000).toISOString().slice(0, 10);
        return {
            id: `${n}-${topic.id}-${i + 1}`,
            n, topic: topic.id, index: i + 1,
            ...topic.gen(seededRng(`${n}:${topic.id}:${i}`)),
            level, date,
            solved: int(meta, ...SOLVED_RANGE[level]),
        };
    });
}

export const buildBankMock = (): BankNumber[] =>
    NUMBERS.map(({ n, title, topics }) => ({
        n, title,
        part: n <= PART1 ? 1 : 2,
        topics: topics.map((t) => ({ id: t.id, name: t.name, tasks: tasksOf(n, t) })),
    }));
