const round = (x: number): number => Number(x.toFixed(6));
/** Число в условии: десятичная запятая и пробелы в разрядах, как на ЕГЭ */
const num = (x: number): string =>
    round(x).toLocaleString('ru-RU', { maximumFractionDigits: 6 }).replace(/\s/g, '\\ ').replace(',', '{,}');
/** Слагаемое со знаком: sign(3) → «+ 3», sign(-3) → «- 3» */
const sign = (x: number): string => (x < 0 ? `- ${-x}` : `+ ${x}`);
/** Слагаемое kx со знаком: 1 → «+ x», -1 → «- x», 3 → «+ 3x» */
const lin = (k: number, v = 'x'): string => (Math.abs(k) === 1 ? `${k < 0 ? '-' : '+'} ${v}` : `${sign(k)}${v}`);
/** Число в формуле, отрицательное — в скобках: par(-3) → «(-3)» */
const par = (x: number): string => (x < 0 ? `(${x})` : `${x}`);
const gcd = (a: number, b: number): number => (b ? gcd(b, a % b) : a);

